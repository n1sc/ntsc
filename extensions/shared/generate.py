#!/usr/bin/env python3
"""Generate client metadata and lexical highlighting from the compiler's keywords."""

import argparse
import json
import plistlib
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CONTRACT = json.loads((ROOT / "extensions/shared/contract.json").read_text())
RELEASE = json.loads((ROOT / "extensions/shared/release.json").read_text())
TOKEN_SOURCE = (ROOT / "crates/ntsc-ast/src/token.rs").read_text()
KEYWORDS = sorted(set(re.findall(r'=> Some\("([a-z]+)"\)', TOKEN_SOURCE)))
TYPES = ["int", "float", "string", "bool", "array", "object", "option", "result", "any", "pointer", "slice"]
CONSTANTS = ["true", "false", "nil", "this", "super"]
CONTROL = [word for word in KEYWORDS if word not in TYPES + CONSTANTS]


def serialized(value):
    return json.dumps(value, indent=2, ensure_ascii=False) + "\n"


def generated_files():
    language = CONTRACT["language"]
    keyword_pattern = r"\b(?:" + "|".join(CONTROL) + r")\b"
    type_pattern = r"\b(?:" + "|".join(TYPES) + r")\b"
    constant_pattern = r"\b(?:" + "|".join(CONSTANTS) + r")\b"
    grammar = {
        "name": language["name"],
        "scopeName": language["scope"],
        "fileTypes": ["nt"],
        "patterns": [
            {"name": "comment.line.number-sign.neutron", "match": "#.*$"},
            {
                "name": "string.quoted.double.neutron",
                "begin": '"',
                "end": '"',
                "patterns": [
                    {"name": "constant.character.escape.neutron", "match": r"\\."},
                    {
                        "name": "meta.interpolation.neutron",
                        "begin": r"\$\{",
                        "end": r"\}",
                        "patterns": [{"include": "$self"}],
                    },
                ],
            },
            {"name": "keyword.control.neutron", "match": keyword_pattern},
            {"name": "storage.type.neutron", "match": type_pattern},
            {"name": "constant.language.neutron", "match": constant_pattern},
            {"name": "entity.name.function.neutron", "match": r"\b[A-Za-z_][A-Za-z_0-9]*(?=\s*\()"},
            {"name": "entity.name.namespace.neutron", "match": r"@[A-Za-z_][A-Za-z_0-9]*"},
            {
                "name": "constant.numeric.neutron",
                "match": r"\b(?:0[xX][0-9a-fA-F_]+|0[bB][01_]+|0[oO][0-7_]+|\d[\d_]*(?:\.[\d_]+)?(?:[eE][+-]?[\d_]+)?)\b",
            },
        ],
    }
    yield "extensions/vscode/contract.json", serialized(CONTRACT)
    yield "extensions/vscode/syntaxes/neutron.tmLanguage.json", serialized(grammar)
    yield "extensions/vscode/language-configuration.json", serialized({
        "comments": {"lineComment": language["lineComment"]},
        "brackets": [["{", "}"], ["[", "]"], ["(", ")"]],
        "autoClosingPairs": [
            {"open": opening, "close": closing, "notIn": ["string", "comment"]}
            for opening, closing in [("{", "}"), ("[", "]"), ("(", ")"), ('"', '"')]
        ],
        "surroundingPairs": [["{", "}"], ["[", "]"], ["(", ")"], ['"', '"']],
        "indentationRules": {
            "increaseIndentPattern": r"^.*\{[^}]*$",
            "decreaseIndentPattern": r"^\s*\}",
        },
    })
    yield "extensions/other/sublime/Neutron.tmLanguage", plistlib.dumps(grammar).decode()
    vim_syntax = (
        '" Generated by extensions/shared/generate.py.\n'
        'if exists("b:current_syntax") | finish | endif\n'
        f'syntax keyword neutronKeyword {" ".join(CONTROL)}\n'
        f'syntax keyword neutronType {" ".join(TYPES)}\n'
        f'syntax keyword neutronConstant {" ".join(CONSTANTS)}\n'
        'syntax match neutronComment "#.*$"\n'
        'syntax match neutronEscape "\\\\\\\\." contained\n'
        'syntax region neutronString start=+"+ skip=+\\\\\\\\\\|\\\\"+ end=+"+ contains=neutronEscape\n'
        'syntax match neutronNumber "\\<\\d[0-9A-Fa-f_xXbBoO.]*\\>"\n'
        'highlight default link neutronKeyword Keyword\n'
        'highlight default link neutronType Type\n'
        'highlight default link neutronConstant Constant\n'
        'highlight default link neutronComment Comment\n'
        'highlight default link neutronString String\n'
        'highlight default link neutronEscape SpecialChar\n'
        'highlight default link neutronNumber Number\n'
        'let b:current_syntax = "neutron"\n'
    )
    yield "extensions/nvim/syntax/neutron.vim", vim_syntax
    yield "extensions/other/vim/syntax/neutron.vim", vim_syntax
    lua_contract = (
        "-- Generated by extensions/shared/generate.py.\nreturn {\n"
        f'  server_id = "{CONTRACT["server"]["id"]}",\n'
        f'  cmd = {{ "{CONTRACT["server"]["command"]}", "lsp" }},\n'
        f'  marker = "{language["projectMarker"]}",\n'
        f'  cli = "{CONTRACT["cli"]}",\n'
        "  workflows = {\n"
        + "".join(f'    {name} = {{ "{args[0]}" }},\n' for name, args in CONTRACT["workflows"].items())
        + "  },\n}\n"
    )
    yield "extensions/nvim/lua/neutron/contract.lua", lua_contract
    yield "extensions/zed/src/contract.rs", (
        "// Generated by extensions/shared/generate.py.\n"
        f'pub const SERVER_COMMAND: &str = {json.dumps(CONTRACT["server"]["command"])};\n'
        'pub const SERVER_ARGUMENTS: &[&str] = &["lsp"];\n'
    )
    yield "extensions/other/vim/autoload/neutron/contract.vim", (
        '" Generated by extensions/shared/generate.py.\n'
        "function! neutron#contract#get() abort\n"
        f"  return {json.dumps(CONTRACT)}\nendfunction\n"
    )
    yield "extensions/emacs/neutron-data.el", (
        ";;; neutron-data.el --- Generated shared metadata -*- lexical-binding: t; -*-\n"
        f"(defconst neutron--server-command '({json.dumps(CONTRACT['server']['command'])} \"lsp\"))\n"
        f"(defconst neutron--project-marker {json.dumps(language['projectMarker'])})\n"
        f"(defconst neutron--cli {json.dumps(CONTRACT['cli'])})\n"
        f"(defconst neutron--keywords '({' '.join(json.dumps(word) for word in CONTROL)}))\n"
        f"(defconst neutron--types '({' '.join(json.dumps(word) for word in TYPES)}))\n"
        f"(defconst neutron--constants '({' '.join(json.dumps(word) for word in CONSTANTS)}))\n"
        "(defconst neutron--workflows\n  '("
        + " ".join(f'({name} . ({json.dumps(args[0])}))' for name, args in CONTRACT["workflows"].items())
        + "))\n(provide 'neutron-data)\n;;; neutron-data.el ends here\n"
    )
    yield "extensions/zed/languages/neutron/config.toml", (
        'name = "Neutron"\ngrammar = "neutron"\npath_suffixes = ["nt"]\n'
        'line_comments = ["# "]\ntab_size = 4\nhard_tabs = false\n'
        'autoclose_before = ";:.,=}])"\n'
        'brackets = [\n'
        '  { start = "{", end = "}", close = true, newline = true },\n'
        '  { start = "[", end = "]", close = true, newline = false },\n'
        '  { start = "(", end = ")", close = true, newline = false },\n'
        '  { start = "\\\"", end = "\\\"", close = true, newline = false, not_in = ["string", "comment"] },\n'
        ']\n'
    )
    yield "extensions/zed/languages/neutron/tasks.json", serialized([
        {
            "label": f"Neutron: {name.title()}",
            "command": CONTRACT["cli"],
            "args": args,
            "cwd": "$ZED_WORKTREE_ROOT",
            "use_new_terminal": False,
            "allow_concurrent_runs": False,
            "reveal": "always",
            "save": "all",
        }
        for name, args in CONTRACT["workflows"].items()
    ])
    yield "extensions/shared/tree-sitter-neutron/grammar.js", (
        "// Generated lexical grammar; semantic analysis stays in ntsc lsp.\n"
        "module.exports = grammar({\n"
        "  name: 'neutron',\n"
        "  extras: $ => [/\\s/, $.comment],\n"
        "  word: $ => $.identifier,\n"
        "  rules: {\n"
        "    source_file: $ => repeat($._item),\n"
        "    _item: $ => choice($.keyword, $.type, $.constant, $.identifier, $.number, $.string,\n"
        "      $.namespace, $.block, $.parentheses, $.brackets, $.operator),\n"
        "    block: $ => seq('{', repeat($._item), '}'),\n"
        "    parentheses: $ => seq('(', repeat($._item), ')'),\n"
        "    brackets: $ => seq('[', repeat($._item), ']'),\n"
        f"    keyword: _ => choice({', '.join(json.dumps(word) for word in CONTROL)}),\n"
        f"    type: _ => choice({', '.join(json.dumps(word) for word in TYPES)}),\n"
        f"    constant: _ => choice({', '.join(json.dumps(word) for word in CONSTANTS)}),\n"
        "    identifier: _ => /[A-Za-z_][A-Za-z_0-9]*/,\n"
        "    namespace: _ => /@[A-Za-z_][A-Za-z_0-9]*/,\n"
        "    number: _ => /(?:0[xX][0-9a-fA-F_]+|0[bB][01_]+|0[oO][0-7_]+|[0-9][0-9_]*(?:\\.[0-9_]+)?(?:[eE][+-]?[0-9_]+)?)/,\n"
        "    comment: _ => token(seq('#', /[^\\n]*/)),\n"
        "    string: $ => seq('\"', repeat(choice($.escape, $.interpolation, /[^\"\\\\$]+/, '$')), '\"'),\n"
        "    escape: _ => token(seq('\\\\', /./)),\n"
        "    interpolation: $ => seq('${', repeat($._item), '}'),\n"
        "    operator: _ => token(choice('...', '..', '?.', '->', '=>', '==', '!=', '<=', '>=',\n"
        "      '++', '--', '&&', '||', '<<', '>>', '|>', '<|', '+', '-', '*', '/', '%', '=',\n"
        "      '<', '>', '!', '&', '|', '^', '~', '?', ':', ';', ',', '.', '@')),\n"
        "  },\n});\n"
    )
    highlights = (
        "(keyword) @keyword\n(type) @type.builtin\n(constant) @constant.builtin\n"
        "(identifier) @variable\n(namespace) @namespace\n(number) @number\n"
        "(string) @string\n(escape) @string.escape\n(comment) @comment\n"
        "(operator) @operator\n[\"{\" \"}\" \"(\" \")\" \"[\" \"]\"] @punctuation.bracket\n"
    )
    yield "extensions/zed/languages/neutron/highlights.scm", highlights
    yield "extensions/other/helix/runtime/queries/neutron/highlights.scm", highlights
    yield "extensions/other/helix/languages.toml", (
        '[language-server.ntsc]\ncommand = "ntsc"\nargs = ["lsp"]\n\n'
        '[[language]]\nname = "neutron"\nscope = "source.neutron"\nfile-types = ["nt"]\n'
        'roots = ["neutron.toml"]\ncomment-token = "#"\nlanguage-servers = ["ntsc"]\n'
        'indent = { tab-width = 4, unit = "    " }\n\n'
        '[[grammar]]\nname = "neutron"\n'
        f'source = {{ git = "{RELEASE["grammar"]["repository"]}.git", rev = "{RELEASE["grammar"]["rev"]}", subpath = "extensions/shared/tree-sitter-neutron" }}\n'
    )
    yield "extensions/other/helix/config.toml", (
        "# Optional bindings; merge into your existing Helix configuration.\n"
        "[keys.normal.space.n]\n"
        + "".join(
            f'{name[0]} = [":write-all", ":sh {CONTRACT["cli"]} {" ".join(args)}"]\n'
            for name, args in CONTRACT["workflows"].items()
        )
        + 'f = ":format"\ns = ":lsp-restart"\n'
    )
    yield "extensions/other/sublime/LSP-neutron.sublime-settings", serialized({
        "command": [CONTRACT["server"]["command"], *CONTRACT["server"]["args"]],
        "selector": "source.neutron",
        "enabled": True,
    })
    yield "extensions/other/sublime/contract.json", serialized(CONTRACT)
    for name, args in CONTRACT["workflows"].items():
        yield f"extensions/other/sublime/Neutron-{name.title()}.sublime-build", serialized({
            "cmd": [CONTRACT["cli"], *args],
            "working_dir": "${folder}",
            "selector": language["scope"],
        })
    license_text = (ROOT / "LICENSE").read_text()
    for directory in ["vscode", "nvim", "emacs", "other/vim", "other/sublime", "other/helix", "shared/tree-sitter-neutron"]:
        yield f"extensions/{directory}/LICENSE", license_text


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    stale = []
    for relative, content in generated_files():
        path = ROOT / relative
        if arguments.check:
            if not path.exists() or path.read_text() != content:
                stale.append(relative)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        parser.exit(1, "Stale generated editor files:\n" + "\n".join(stale) + "\n")


if __name__ == "__main__":
    main()
